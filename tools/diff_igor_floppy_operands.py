#!/usr/bin/env python3
"""Operand-level diff of 'same'/'revised' floppy functions against the CD.

Input: floppy-research/function-comparison.json (from audit_igor_floppy_functions.py).
For each pair with similarity >= 0.85 the two instruction streams are aligned
on their shapes. Reported per pair:
  * constant_changes: aligned instructions whose non-memory operands differ
    (immediates, registers); memory operands and jump/call targets are masked
    because the builds are linked differently;
  * cd_only / floppy_only: instruction runs present on one side only.
Pairs with no change are listed as identical. Triage output, not proof.

Output: floppy-research/operand-diff.json and .md
Usage: diff_igor_floppy_operands.py [repo-root]
"""
import collections
import difflib
import json
import re
import sys
from pathlib import Path

from capstone import Cs, CS_ARCH_X86, CS_MODE_16

root = Path(sys.argv[1] if len(sys.argv) > 1 else '.')
sys.path.insert(0, str(root / 'scripts'))
from ne_disasm import read_segment_table  # noqa: E402

ROW = re.compile(r'\{\s*(\w+),\s*(0x[\da-f]+),\s*(0x[\da-f]+|\d+)\s*\}')
md = Cs(CS_ARCH_X86, CS_MODE_16)
dat = (root / 'IGOR/IGOR.DAT').read_bytes()
cdexe = (root / 'IGOR-CD/IGOR.EXE').read_bytes()
_, segs = read_segment_table(str(root / 'IGOR-CD/IGOR.EXE'))
ov = json.loads((root / 'floppy-research/overlays.json').read_text())
pairs = json.loads((root / 'floppy-research/function-comparison.json').read_text())


def func(blob, start):
    ins = []
    for i in md.disasm(blob[start:start + 20000], start):
        ins.append((i.address, i.mnemonic, i.op_str))
        if i.mnemonic.startswith('ret'):
            break
    return ins


def mask(op):
    return re.sub(r'\[[^]]+\]', '[mem]', op)


def shape(ins):
    return [m + ' ' + ('@' if m.startswith('j') or m in ('call', 'lcall') else mask(o))
            for _, m, o in ins]


POINTER_REGS = ('di', 'si', 'bx')


def pointer_like(x, y):
    """Relocated addresses: unrelocated segment words (0xffff) and pointer loads."""
    if '0xffff' in (x[2] + y[2]):
        return True
    if x[2] == 'ax, 0xa000' and y[1] == 'mov' and '[' in y[2]:
        return True  # video segment constant vs a variable holding it
    if x[1] == 'mov' and x[2].split(',')[0] in POINTER_REGS and \
            y[2].split(',')[0] in POINTER_REGS:
        return True
    return False


def fmt(a):
    return '%04X %s %s' % a


out = []
for r in pairs:
    if r.get('similarity', 0) < .85:
        continue
    v = ov[r['overlay'] - 1]
    f = func(dat[v['offset']:v['offset'] + v['size']], int(r['floppy_offset'], 16))
    o, sz = segs[r['cd_segment']][0], segs[r['cd_segment']][1]
    c = func(cdexe[o:o + sz], int(r['cd_offset'], 16))
    fs, cs = shape(f), shape(c)
    sm = difflib.SequenceMatcher(None, fs, cs, autojunk=False)
    changes, fonly, conly, suppressed = [], [], [], 0
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag == 'equal':
            continue
        if tag == 'replace' and (i2 - i1) == (j2 - j1):
            for x, y in zip(f[i1:i2], c[j1:j2]):
                if x[1] == y[1]:
                    if pointer_like(x, y):
                        suppressed += 1
                    else:
                        changes.append((fmt(x), fmt(y)))
                else:
                    fonly.append(fmt(x))
                    conly.append(fmt(y))
        else:
            fonly += [fmt(x) for x in f[i1:i2]]
            conly += [fmt(y) for y in c[j1:j2]]
    # equal-shape blocks can still differ in constants only when the mnemonic
    # matches but the operand text differs after masking, which shape() keeps,
    # so 'replace' covers constant changes.
    out.append(dict(state=r['state'], part=r['part'], overlay=r['overlay'],
                    floppy=r['floppy_offset'], cd='%d:%s' % (r['cd_segment'], r['cd_offset']),
                    similarity=r['similarity'], pointer_like_suppressed=suppressed,
                    constant_changes=changes,
                    floppy_only=fonly, cd_only=conly))

(root / 'floppy-research/operand-diff.json').write_text(json.dumps(out, indent=1) + '\n')
per = collections.defaultdict(lambda: collections.Counter())
for r in out:
    p = per[r['part']]
    p['functions'] += 1
    p['identical'] += not (r['constant_changes'] or r['floppy_only'] or r['cd_only'])
    p['constant_changes'] += len(r['constant_changes'])
    p['floppy_only'] += len(r['floppy_only'])
    p['cd_only'] += len(r['cd_only'])
lines = ['# Operand-level differences (similar functions)\n',
         'Generated by `tools/diff_igor_floppy_operands.py` for pairs with shape similarity '
         '>= 0.85. Memory operands, jump/call targets and pointer-like operands are masked. Counts are instructions.\n',
         '| Part | Functions | Identical after masking | Operand changes | Floppy-only | CD-only |',
         '| --- | --- | --- | --- | --- | --- |']
for part in sorted(per):
    p = per[part]
    lines.append('| %d | %d | %d | %d | %d | %d |' % (part, p['functions'], p['identical'],
                                                  p['constant_changes'], p['floppy_only'],
                                                  p['cd_only']))
lines += ['', '## Operand changes in aligned instructions', '',
          '| State | Floppy | CD | Floppy instruction | CD instruction |',
          '| --- | --- | --- | --- | --- |']
for r in out:
    for a, b in r['constant_changes']:
        lines.append('| %d | %s | %s | `%s` | `%s` |' % (r['state'], r['floppy'], r['cd'], a, b))
(root / 'floppy-research/operand-diff.md').write_text('\n'.join(lines) + '\n')
print(len(out), 'pairs;', sum(1 for r in out if not (r['constant_changes'] or r['floppy_only'] or r['cd_only'])), 'identical')
