#!/usr/bin/env python3
"""Write one listing per Spanish floppy state under code-floppy/es/.

Each state's routine is export 0 of the overlay that the floppy dispatcher
(floppy-research/dispatcher-states.json) selects. The listing is a linear
16-bit disassembly of that overlay's code as stored in IGOR.DAT, with:
  * a header (state, part, overlay, file position, size, exports, fixups);
  * far calls resolved to overlay number + export, or marked as resident code;
  * segment words listed in the overlay's fixup table marked with '*'.
States that share an overlay point to the first state's listing.

Linear sweep can desynchronise over data embedded in code; undecodable bytes
are listed as 'db'. Treat jump tables and strings in the output as data.

Usage: generate_igor_floppy_state_listings.py [repo-root]
"""
import json
import struct
import sys
import hashlib
from pathlib import Path

from capstone import Cs, CS_ARCH_X86, CS_MODE_16

root = Path(sys.argv[1] if len(sys.argv) > 1 else '.')
dat = (root / 'IGOR/IGOR.DAT').read_bytes()
mem = (root / 'floppy-research/unpacked-memory.bin').read_bytes()
ov = json.loads((root / 'floppy-research/overlays.json').read_text())
states = json.loads((root / 'floppy-research/dispatcher-states.json').read_text())
out = root / 'code-floppy/es'
out.mkdir(parents=True, exist_ok=True)

BASE = 0x10100
PATCHED = {289: 'IGOR.DAT byte A1BD05 differs from the original (74 -> EB)'}

for j, v in enumerate(ov):
    v['num'] = j + 1
    v['seg'] = (v['memory'] - BASE) // 16
    v['exports'] = [struct.unpack_from('<H', mem, v['memory'] + 34 + i * 5)[0]
                    for i in range(v['count'])]
by_seg = {v['seg']: v for v in ov}

md = Cs(CS_ARCH_X86, CS_MODE_16)
md.skipdata = True
md.skipdata_setup = ('db', None, None)


def overlay_code(v):
    code = dat[v['offset']:v['offset'] + v['size']]
    rel = dat[v['offset'] + v['size']:v['offset'] + v['size'] + v['relsize']]
    fix = set(struct.unpack('<%dH' % (len(rel) // 2), rel))
    return code, fix


def describe_far(seg, off):
    t = by_seg.get(seg)
    if t is None:
        return 'resident %04X:%04X' % (seg, off)
    k, r = divmod(off - 0x20, 5)
    if off >= 0x20 and r == 0 and k < t['count']:
        return 'overlay %d export %d (+%04X)' % (t['num'], k, t['exports'][k])
    return 'overlay %d stub +%04X' % (t['num'], off)


def listing(v):
    code, fix = overlay_code(v)
    lines = []
    for i in md.disasm(code, 0):
        note = ''
        if i.bytes[0] == 0x9A and len(i.bytes) == 5:
            off, seg = struct.unpack_from('<HH', i.bytes, 1)
            mark = '*' if (i.address + 3) in fix else ' '
            note = '  ; far call%s %s' % (mark, describe_far(seg, off))
        lines.append('%04X  %-24s %-6s %s%s' % (
            i.address, i.bytes.hex(' '), i.mnemonic, i.op_str, note))
    return '\n'.join(lines) + '\n'


first = {}
index = []
for key in sorted(states, key=int):
    st = int(key)
    n = states[key]['overlay']
    v = ov[n - 1]
    part = st // 10
    name = 'part_%02d_state_%d.asm' % (part, st)
    head = [
        '; Spanish floppy state %d (part %d)' % (st, part),
        '; overlay %d, export 0, IGOR.DAT position %d (0x%X), %d code bytes, %d fixups'
        % (n, v['offset'], v['offset'], v['size'], v['relsize'] // 2),
        '; overlay exports (code offsets): %s' % ', '.join('%04X' % e for e in v['exports']),
        '; sha1 of code: %s' % hashlib.sha1(dat[v['offset']:v['offset'] + v['size']]).hexdigest(),
    ]
    cd = states[key].get('cd_segment')
    head.append('; CD counterpart segment: %s' % (cd if cd is not None else 'none'))
    if n in PATCHED:
        head.append('; NOTE: %s' % PATCHED[n])
    if n in first:
        head.append('; This state shares overlay %d with state %d: see %s'
                    % (n, first[n][0], first[n][1]))
        body = ''
    else:
        first[n] = (st, name)
        body = listing(v)
    (out / name).write_text('\n'.join(head) + '\n\n' + body)
    index.append((st, n, name, cd, v['size']))

(out / 'INDEX.md').write_text(
    '# Spanish floppy state listings\n\n'
    'Generated by `tools/generate_igor_floppy_state_listings.py`.\n\n'
    '| State | Part | Overlay | Code bytes | CD segment | Listing |\n'
    '| --- | --- | --- | --- | --- | --- |\n' +
    ''.join('| %d | %d | %d | %d | %s | %s |\n' % (s, s // 10, n, sz, cd or '-', f)
            for s, n, f, cd, sz in index))
print('wrote', len(index), 'state files,', len(first), 'unique overlays to', out)
