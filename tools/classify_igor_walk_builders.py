#!/usr/bin/env python3
"""Classify each room's local walk-path builder: area-routed ('full') or direct ('simple').

A builder is a function with a 0xA-byte frame that returns at once when the
source and destination points are equal (the engine's buildWalkPath and
buildWalkPathSimple). It is 'full' when it also does the layer lookup
(multiplies by 0x140) that selects the start and destination areas. Run on the
Spanish floppy overlays and on the CD segments they correspond to.

Output: floppy-research/walk-builders.md. Triage by pattern, not proof.
Usage: classify_igor_walk_builders.py [repo-root]  (run from the repo root)
"""
import json,re,sys,collections
sys.path.insert(0,'scripts')
from ne_disasm import read_segment_table
from pathlib import Path
from capstone import *
md=Cs(CS_ARCH_X86,CS_MODE_16)
dat=Path('IGOR/IGOR.DAT').read_bytes();cdexe=Path('IGOR-CD/IGOR.EXE').read_bytes()
_,segs=read_segment_table('IGOR-CD/IGOR.EXE')
ov=json.load(open('floppy-research/overlays.json'))
states=json.load(open('floppy-research/dispatcher-states.json'))
def funcs(blob):
    for m in re.finditer(b'\x55\x89\xe5',blob):
        s=m.start();ins=[]
        for i in md.disasm(blob[s:s+20000],s):
            ins.append((i.address,i.mnemonic,i.op_str))
            if i.mnemonic.startswith('ret'):break
        if ins and ins[-1][1].startswith('ret'): yield s,ins
def classify(ins):
    t=[o for _,m,o in ins]
    if len(ins)<6 or not t[1].startswith('mov ax, 0xa') and t[1]!='mov ax, 0xa': pass
    # frame 0xa, equal-point early out
    txt=' ; '.join(f'{m} {o}' for _,m,o in ins[:14])
    if 'mov ax, 0xa' not in txt or 'sub sp, 0xa' not in txt: return None
    if not ('word ptr [bp + 0xc]' in ' '.join(t) and 'word ptr [bp + 8]' in ' '.join(t)): return None
    full=any(o=='ax, 0x140' for _,m,o in ins) or any(' 0x140' in o and m in('mul','imul') for _,m,o in ins)
    return 'full' if full else 'simple'
res={}
seen=set()
for k,v in sorted(states.items(),key=lambda x:int(x[0])):
    n,cs=v['overlay'],v['cd_segment']
    if (n,cs) in seen:continue
    seen.add((n,cs))
    o=ov[n-1];fb=dat[o['offset']:o['offset']+o['size']]
    fl=[(s,classify(i)) for s,i in funcs(fb)];fl=[(s,c) for s,c in fl if c]
    cl=[]
    if cs in segs:
        so,sz=segs[cs][0],segs[cs][1]
        cl=[(s,classify(i)) for s,i in funcs(cdexe[so:so+sz])];cl=[(s,c) for s,c in cl if c]
    res[int(k)]=(n,cs,[(f'{s:04X}',c) for s,c in fl],[(f'{s:04X}',c) for s,c in cl])
lines=['# Room walk builders: floppy versus CD\n',
 'Generated by `tools/classify_igor_walk_builders.py`. full = area-routed, simple = direct. A heuristic.\n',
 '| State | Overlay | CD seg | Floppy | CD | Same? |','| --- | --- | --- | --- | --- | --- |']
diff=[]
for k,(n,cs,f,c) in res.items():
    fc=','.join(x[1] for x in f) or '-';cc=','.join(x[1] for x in c) or '-'
    same='' if fc=='-' or cc=='-' else ('yes' if fc==cc else 'NO')
    if same=='NO': diff.append(k)
    lines.append('| %d | %d | %s | %s | %s | %s |'%(k,n,cs or '-',fc,cc,same))
lines.append('\nDifferent builder type: %s'%(', '.join(map(str,diff)) or 'none'))
Path('floppy-research/walk-builders.md').write_text('\n'.join(lines)+'\n')
print('different:',diff)
