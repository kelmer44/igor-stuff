FORK = sys.argv[1]
PARTS = list(range(51, 68))
FRAMES = {"flame103": "kMazeFlameFixed", "flame107": "kMazeFlameFirstFrame", "flame108": "kMazeFlameLayer1"}
FACING = {1: "kFacingPositionBack", 2: "kFacingPositionRight", 3: "kFacingPositionFront", 4: "kFacingPositionLeft"}


def main():
	exe, nseg = ne_segments()
	base, size = nseg(231)
	ds = exe[base:base + size]
	nodes = [tuple(ds[5421 + i * 5:5421 + i * 5 + 5]) for i in range(108)]
	rooms = {p: parse_room(p) for p in PARTS}

	# resources: the picture sets are shared by the rooms of the same loader
	sets = {}
	for p in PARTS:
		r = rooms[p]
		key = r["info"]["loader"]
		sets.setdefault(key, []).append(p)
	setNames = {}
	for key, parts in sets.items():
		setNames[key] = "MazeEntrance" if 67 in parts else "Maze%d" % parts[0]
	resources = []   # (name, offset, size)
	ids = {}
	nextId = 998
	idsOf = {}

	def addRes(kind, name, off, size):
		global_ = None
		return None
	order = ["TXT", "IMG", "PAL", "MSK", "BOX"]
	done = set()
	rows = []
	for p in PARTS:
		r = rooms[p]
		loader = r["info"]["loader"]
		idsOf[p] = {}
		off, sz = r["res"]["DAT"]
		name = "DAT_Maze%d" % p
		if p == 67:
			name = "DAT_MazeEntrance"   # already in the table
		else:
			rows.append((name, nextId, off, sz))
			nextId += 1
		idsOf[p]["DAT"] = name
		if loader not in done:
			done.add(loader)
			for k in order:
				off, sz = r["res"][k]
				name = "%s_%s" % (k, setNames[loader])
				if setNames[loader] == "MazeEntrance":
					continue
				rows.append((name, nextId, off, sz))
				nextId += 1
		for k in order:
			idsOf[p][k] = "%s_%s" % (k, setNames[loader])
	return rooms, nodes, rows, idsOf, setNames


