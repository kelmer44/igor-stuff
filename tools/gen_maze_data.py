def patch(path, begin, end, lines, anchor_after=None, anchor_before=None, encoding="utf-8"):
	text = open(path, encoding=encoding).read()
	block = begin + "\n" + "\n".join(lines) + "\n" + end + "\n"
	if begin in text:
		a = text.index(begin)
		b = text.index(end) + len(end) + 1
		text = text[:a] + block + text[b:]
	elif anchor_after:
		i = text.index(anchor_after)
		i = text.index("\n", i) + 1
		text = text[:i] + block + text[i:]
	else:
		i = text.index(anchor_before)
		text = text[:i] + block + text[i:]
	open(path, "w", encoding=encoding).write(text)


def apply_resources(rows):
	tool = os.path.join(ROOT, "reference", "scummvm-create-igortbl")
	for name in ("resource_sp_cdrom.h", "resource_ids_extra.h"):
		p = os.path.join(tool, name)
		t = open(p, encoding="latin-1").read().replace("UndergroundCorridor", "MazeEntrance")
		open(p, "w", encoding="latin-1").write(t)
	patch(os.path.join(tool, "resource_ids_extra.h"), "// MAZE ROOMS BEGIN", "// MAZE ROOMS END",
	      ["#define %s %d" % (n, i) for n, i, o, z in rows], anchor_after="#define BOX_MazeEntrance", encoding="latin-1")
	patch(os.path.join(tool, "resource_sp_cdrom.h"), "// MAZE ROOMS BEGIN", "// MAZE ROOMS END",
	      ["{ %s, 0x%x, %d }," % (n, o, z) for n, i, o, z in rows], anchor_after="{ BOX_MazeEntrance", encoding="latin-1")
	patch(os.path.join(FORK, "resource_ids.h"), "// MAZE ROOMS BEGIN", "// MAZE ROOMS END",
	      ["#define %s %d // IGOR.EXE:0x%X, 0x%04X bytes" % (n, i, o, z) for n, i, o, z in rows], anchor_after="#define BOX_MazeEntrance")


