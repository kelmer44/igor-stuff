#!/usr/bin/env python3
"""Pair Spanish floppy room functions with CD functions and compare them.

Follows the English-floppy audit's method (audit/2026-10-15/english-floppy):
functions are found by compiler prologue (push bp; mov bp,sp) up to the first
return, outside catalogued resource bytes. A floppy function is compared with
every CD function of the CD segment its state overlay corresponds to
(dispatcher-states.json). The shape of an instruction keeps mnemonic and
register/constant operands, masks memory operands, and replaces jump and call
targets. The best match above the size filter is reported.

This is a triage aid, not proof of equivalence.

Output: floppy-research/function-comparison.json and .md
Usage: audit_igor_floppy_functions.py [repo-root]
"""
import collections
import difflib
import json
import re
import struct
import sys
from pathlib import Path

from capstone import Cs, CS_ARCH_X86, CS_MODE_16

root = Path(sys.argv[1] if len(sys.argv) > 1 else '.')
sys.path.insert(0, str(root / 'scripts'))
from ne_disasm import read_segment_table  # noqa: E402

ROW = re.compile(r'\{\s*(\w+),\s*(0x[\da-f]+),\s*(0x[\da-f]+|\d+)\s*\}')


def rows(name):
    text = (root / 'reference/scummvm-create-igortbl' / name).read_text()
    return [(int(o, 0), int(s, 0)) for _, o, s in ROW.findall(text)]


md = Cs(CS_ARCH_X86, CS_MODE_16)
dat = (root / 'IGOR/IGOR.DAT').read_bytes()
cdexe = (root / 'IGOR-CD/IGOR.EXE').read_bytes()
_, segs = read_segment_table(str(root / 'IGOR-CD/IGOR.EXE'))
ov = json.loads((root / 'floppy-research/overlays.json').read_text())
states = json.loads((root / 'floppy-research/dispatcher-states.json').read_text())
frows = rows('resource_sp_floppy.h')
crows = rows('resource_sp_cdrom.h')


def banned(rs, base, size):
    return [(o - base, o - base + z) for o, z in rs if base <= o < base + size]


def functions(blob, ban=()):
    result = {}
    for m in re.finditer(b'\x55\x89\xe5', blob):
        start = m.start()
        if any(a <= start < b for a, b in ban):
            continue
        ins = []
        for i in md.disasm(blob[start:start + 20000], start):
            ins.append((i.address, i.mnemonic, i.op_str))
            if i.mnemonic.startswith('ret'):
                break
        if ins and ins[-1][1].startswith('ret'):
            result[start] = ins
    return result


def shape(ins):
    out = []
    for _, mn, op in ins:
        if mn.startswith('j') or mn in ('call', 'lcall'):
            op = '@'
        else:
            op = re.sub(r'\[[^]]+\]', '[mem]', op)
        out.append(mn + ' ' + op)
    return out


cd_cache = {}


def cd_functions(cs):
    if cs not in cd_cache:
        o, sz = segs[cs][0], segs[cs][1]
        blob = cdexe[o:o + sz]
        cd_cache[cs] = {a: (i, shape(i)) for a, i in functions(blob, banned(crows, o, sz)).items()}
    return cd_cache[cs]


seen = {}
results = []
for key in sorted(states, key=int):
    st = int(key)
    n, cs = states[key]['overlay'], states[key]['cd_segment']
    if (n, cs) in seen:
        continue
    seen[(n, cs)] = st
    v = ov[n - 1]
    blob = dat[v['offset']:v['offset'] + v['size']]
    ff = functions(blob, banned(frows, v['offset'], v['size']))
    cands = cd_functions(cs) if cs in segs else {}
    for addr, ins in ff.items():
        sh = shape(ins)
        best = None
        for caddr, (cins, csh) in cands.items():
            if min(len(cins), len(ins)) / max(len(cins), len(ins)) < .7:
                continue
            r = difflib.SequenceMatcher(None, sh, csh, autojunk=False).ratio()
            if best is None or r > best[0]:
                best = (r, caddr, len(cins))
        row = dict(state=st, part=st // 10, overlay=n, floppy_offset='%04X' % addr,
                   floppy_instructions=len(ins), cd_segment=cs)
        if best:
            row.update(cd_offset='%04X' % best[1], cd_instructions=best[2],
                       similarity=round(best[0], 4))
        results.append(row)
    print(st, n, cs, len(ff), file=sys.stderr)


def band(r):
    s = r.get('similarity')
    if s is None:
        return 'no CD counterpart'
    return 'same' if s >= .98 else ('revised' if s >= .85 else ('weak' if s >= .6 else 'new'))


for r in results:
    r['verdict'] = band(r)

(root / 'floppy-research/function-comparison.json').write_text(json.dumps(results, indent=1) + '\n')

by_state = collections.defaultdict(collections.Counter)
for r in results:
    by_state[(r['state'], r['overlay'], r['cd_segment'])][r['verdict']] += 1
lines = ['# Spanish floppy functions vs CD\n',
         'Generated by `tools/audit_igor_floppy_functions.py`. Verdicts: same >= 0.98, '
         'revised >= 0.85, weak >= 0.60, new below that, by shape similarity of the best '
         'CD function in the corresponding segment. A triage hint, not proof.\n',
         '| State | Part | Overlay | CD seg | Functions | same | revised | weak | new | no CD |',
         '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |']
for (st, n, cs), c in sorted(by_state.items()):
    lines.append('| %d | %d | %d | %s | %d | %d | %d | %d | %d | %d |' % (
        st, st // 10, n, cs or '-', sum(c.values()), c['same'], c['revised'], c['weak'],
        c['new'], c['no CD counterpart']))
import statistics
per = collections.defaultdict(list)
for r in results:
    if 'similarity' in r:
        per[r['part']].append(r['similarity'])
lines += ['', '## Per part', '',
          'Different compilers make the shape floor about 0.70 even for the same logic, so '
          'only parts clearly below that are real signals. "Low" = median < 0.65 or a '
          'lower quartile < 0.60.', '',
          '| Part | Functions | Median | Lower quartile | Flag |', '| --- | --- | --- | --- | --- |']
for part in sorted(per):
    v = sorted(per[part])
    med, q1 = statistics.median(v), v[len(v) // 4]
    lines.append('| %d | %d | %.2f | %.2f | %s |' % (part, len(v), med, q1,
                                                   'low' if med < .65 or q1 < .60 else ''))
tot = collections.Counter(r['verdict'] for r in results)
lines.append('\nTotal: %d functions; %s' % (len(results), dict(tot)))
(root / 'floppy-research/function-comparison.md').write_text('\n'.join(lines) + '\n')
print(dict(tot))
